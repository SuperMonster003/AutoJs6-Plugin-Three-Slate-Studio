"""3-Slate Studio device check of the ``samples/`` scripts (roadmap P5.3, P5.4).

Runs the four sample scripts of ``samples/`` unchanged through the AutoJs6 host on one device and checks their outputs
on the PC with ffmpeg. Three steps, so that the maintainer can be called for the dialogs in between:

- ``prepare``: backs up the installed host and plugin APKs (into ``--state``), installs ``--host-apk`` and
  ``--plugin-apk`` when given, grants the plugin all files access through appops (the previous mode is saved), and
  pushes the samples (under ASCII names) and the generated sources (``a.mp4`` 1280x720 10 s, ``b.mp4`` 1280x720 12 s,
  ``bgm.m4a`` 16 s) to ``/sdcard/Download/slate-samples-check``.
- ``run --only edit,compose,flac,gif``: runs each sample through a generated runner (``engines.execScriptFile`` with
  the sample's ``arguments``), waits for the summary JSON the sample writes, pulls the output and prints one line per
  sample (PASS / FAIL, seconds, key values). ``flac`` shows the microphone permission dialog of the host when it is not
  granted yet and ``gif`` always shows the screen capture dialog: the maintainer confirms them on the device. Files the
  samples create in the default folders (``Movies`` / ``Music`` / ``Pictures``, ``AutoJs6`` and ``3-Slate Studio``)
  are deleted afterwards with their MediaStore rows (``--keep`` keeps them).
- ``restore``: reinstalls the saved APKs and checks their md5 (uninstalls a package that was not installed before),
  restores the appops mode and deletes the pushed files.

zh-CN: 3-Slate Studio ``samples/`` 脚本的真机检查 (路线图 P5.3, P5.4). 经 AutoJs6 宿主在一台设备上原样运行 ``samples/`` 的四个样例脚本,
在 PC 上用 ffmpeg 核对输出. 分三步, 以便中途请维护者处理对话框:

- ``prepare``: 备份已装的宿主与插件 APK (放在 ``--state``), 给出 ``--host-apk`` / ``--plugin-apk`` 时安装, 经 appops 授予插件全部
  文件访问权限 (保存原模式), 把样例 (改用 ASCII 文件名) 与生成的素材 (``a.mp4`` 1280x720 10 秒, ``b.mp4`` 1280x720 12 秒, ``bgm.m4a``
  16 秒) 推到 ``/sdcard/Download/slate-samples-check``.
- ``run --only edit,compose,flac,gif``: 每个样例经生成的启动脚本运行 (``engines.execScriptFile`` 带样例的 ``arguments``), 等样例写出
  结果摘要 JSON, 拉回输出, 每个样例输出一行 (PASS / FAIL, 秒数, 关键数值). 宿主尚未获得麦克风权限时 ``flac`` 会弹出授权对话框,
  ``gif`` 每次都弹出屏幕捕获对话框: 由维护者在设备上确认. 样例在默认目录 (``Movies`` / ``Music`` / ``Pictures`` 下的 ``AutoJs6`` 与
  ``3-Slate Studio``) 新建的文件结束后连同 MediaStore 记录删除 (``--keep`` 保留).
- ``restore``: 装回备份的 APK 并核对 md5 (测前未装的包卸载), 还原 appops 模式, 删除推送的文件.

Usage: py -3.12 .python/device_samples_check.py --serial 968e9f18 --state <dir> prepare --host-apk <apk> --plugin-apk <apk>
       py -3.12 .python/device_samples_check.py --serial 968e9f18 --state <dir> run --only edit,compose
       py -3.12 .python/device_samples_check.py --serial 968e9f18 --state <dir> restore
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from device_regression import DEFAULT_FFMPEG, HOST, PLUGIN, RUN_INTENT, adb, ffmpeg, launcher  # noqa: E402
from device_wizard_check import backup, installed, restore  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SAMPLES = ROOT / "samples"
REMOTE = "/sdcard/Download/slate-samples-check"
STAGING = "/data/local/tmp/slate-samples-check"
DEFAULT_FOLDERS = [f"/sdcard/{parent}/{folder}" for parent in ("Movies", "Music", "Pictures") for folder in ("AutoJs6", "3-Slate Studio")]

# key: (sample file, arguments besides output; file names are pushed sources). zh-CN: 键: (样例文件, output 之外的参数; 文件名为推送的素材).
CASES = {
    "edit": ("裁剪加水印再拼接 [v6.8.1+].js", {"a": "a.mp4", "b": "b.mp4"}),
    "compose": ("时间线合成 [v6.8.1+].js", {"a": "a.mp4", "b": "b.mp4", "bgm": "bgm.m4a"}),
    "flac": ("录音转 FLAC [v6.8.1+].js", {"seconds": 5}),
    "gif": ("录屏 10 秒转 GIF [v6.8.1+].js", {"seconds": 10}),
}

RUNNER = """// Generated by .python/device_samples_check.py. zh-CN: 由 .python/device_samples_check.py 生成.
let out = %(out)s;
try {
    if (%(check)s && !video.isAvailable()) {
        files.write(out, JSON.stringify({ ok: false, code: 'PRECHECK_UNAVAILABLE' }));
    } else {
        engines.execScriptFile(%(sample)s, { arguments: %(arguments)s });
    }
} catch (e) {
    files.write(out, JSON.stringify({ ok: false, code: 'RUNNER_ERROR', message: String(e) }));
}
"""


def sources(binary: str, directory: Path) -> dict[str, Path]:
    files = {"a.mp4": directory / "a.mp4", "b.mp4": directory / "b.mp4", "bgm.m4a": directory / "bgm.m4a"}
    if not files["a.mp4"].exists():
        ffmpeg(binary, "-f", "lavfi", "-i", "testsrc2=size=1280x720:rate=30:duration=10", "-f", "lavfi", "-i", "sine=frequency=440:duration=10",
               "-c:v", "libx264", "-pix_fmt", "yuv420p", "-g", "30", "-c:a", "aac", "-b:a", "128k", "-shortest", str(files["a.mp4"]))
    if not files["b.mp4"].exists():
        ffmpeg(binary, "-f", "lavfi", "-i", "smptehdbars=size=1280x720:rate=30:duration=12", "-f", "lavfi", "-i", "sine=frequency=660:duration=12",
               "-c:v", "libx264", "-pix_fmt", "yuv420p", "-g", "30", "-c:a", "aac", "-b:a", "128k", "-shortest", str(files["b.mp4"]))
    if not files["bgm.m4a"].exists():
        ffmpeg(binary, "-f", "lavfi", "-i", "sine=frequency=330:duration=16:sample_rate=44100", "-c:a", "aac", "-b:a", "128k", str(files["bgm.m4a"]))
    return files


def push(serial: str, local: Path, name: str) -> None:
    # Staged in /data/local/tmp, then copied by the shell (see device_regression.py). zh-CN: 先暂存再由 shell 复制 (见 device_regression.py).
    adb(serial, "push", str(local), f"{STAGING}/{name}")
    adb(serial, "shell", f"cp '{STAGING}/{name}' '{REMOTE}/{name}'")


def probe(binary: str, path: Path) -> dict:
    """Duration, codecs, size and (GIF) frame count from the ffmpeg banner. zh-CN: 从 ffmpeg 输出读取时长, 编码, 尺寸与 (GIF) 帧数."""
    done = subprocess.run([binary, "-hide_banner", "-i", str(path), "-map", "0", "-c", "copy", "-f", "null", "-"],
                          capture_output=True, text=True, encoding="utf-8", errors="replace")
    text = done.stderr
    info: dict = {}
    if match := re.search(r"Duration: (\d+):(\d+):(\d+(?:\.\d+)?)", text):
        info["durationMillis"] = round((int(match[1]) * 3600 + int(match[2]) * 60 + float(match[3])) * 1000)
    if match := re.search(r"Video: (\w+)[^\n]*?, (\d{2,5})x(\d{2,5})", text):
        info["video"], info["width"], info["height"] = match[1], int(match[2]), int(match[3])
    if (match := re.search(r"rotation of (-?\d+(?:\.\d+)?) degrees", text)) and "width" in info:
        # media3 may encode a portrait picture in landscape and store the rotation; report the displayed size.
        # zh-CN: media3 可能把竖屏画面按横屏编码并记录旋转; 报告显示尺寸.
        info["rotation"] = round(float(match[1]))
        if info["rotation"] % 180:
            info["width"], info["height"] = info["height"], info["width"]
    if match := re.search(r"Audio: (\w+)[^\n]*?, (\d+) Hz, ([\w.]+)", text):
        info["audio"], info["sampleRate"], info["channels"] = match[1], int(match[2]), match[3]
    frames = re.findall(r"frame=\s*(\d+)", text)
    if frames:
        info["frames"] = int(frames[-1])
    return info


def verdict(key: str, summary: dict, info: dict) -> str | None:
    """None when the output is as the sample promises, otherwise the reason. zh-CN: 输出符合样例说明时为 None, 否则为原因."""
    if not summary.get("ok"):
        return f"summary ok=false code={summary.get('code')} {summary.get('message', '')}".strip()
    duration = info.get("durationMillis", 0)
    if key == "edit":
        # 5 s of a, then all 12 s of b. zh-CN: a 的 5 秒, 再接 b 的全部 12 秒.
        return None if info.get("video") == "h264" and abs(duration - 17000) <= 400 else "expected h264 of about 17000 ms"
    if key == "compose":
        # 8 s + 8 s overlapping 0.5 s = 15.5 s, 1080x1920. zh-CN: 8 秒 + 8 秒重叠 0.5 秒 = 15.5 秒, 1080x1920.
        ok = info.get("video") == "h264" and info.get("audio") == "aac" and (info.get("width"), info.get("height")) == (1080, 1920)
        return None if ok and abs(duration - 15500) <= 400 else "expected h264 / aac 1080x1920 of about 15500 ms"
    if key == "flac":
        return None if info.get("audio") == "flac" and 4000 <= duration <= 7000 else "expected FLAC of about 5000 ms"
    if key == "gif":
        return None if info.get("video") == "gif" and info.get("width") == 480 and info.get("frames", 0) >= 50 else "expected a GIF 480 px wide, 50+ frames"
    return "unknown case"


def listing(serial: str) -> set[str]:
    quoted = " ".join(f"'{folder}'" for folder in DEFAULT_FOLDERS)
    return {line.strip() for line in adb(serial, "shell", f"find {quoted} -type f 2>/dev/null", check=False).splitlines() if line.strip().startswith("/")}


def forget(serial: str, path: str) -> None:
    # MediaStore keeps /storage/emulated/0 paths, so match the part after /sdcard. zh-CN: MediaStore 记的是 /storage/emulated/0 路径, 按 /sdcard 之后的部分匹配.
    suffix = path.removeprefix("/sdcard")
    adb(serial, "shell", "content", "delete", "--uri", "content://media/external/file", "--where", f"\"_data LIKE '%{suffix}'\"", check=False)


def remove_new(serial: str, before: set[str], folders_before: set[str]) -> int:
    created = sorted(listing(serial) - before)
    for path in created:
        adb(serial, "shell", f"rm -f '{path}'", check=False)
        forget(serial, path)
    for folder in DEFAULT_FOLDERS:
        if folder not in folders_before:
            adb(serial, "shell", f"rmdir '{folder}' 2>/dev/null", check=False)
            forget(serial, folder)
    return len(created)


def existing_folders(serial: str) -> set[str]:
    return {folder for folder in DEFAULT_FOLDERS if adb(serial, "shell", f"[ -d '{folder}' ] && echo yes", check=False).strip() == "yes"}


def prepare(args: argparse.Namespace) -> int:
    serial, state = args.serial, args.state
    state.mkdir(parents=True, exist_ok=True)
    saved = {}
    for package, apk in ((HOST, args.host_apk), (PLUGIN, args.plugin_apk)):
        backup_value = backup(serial, package, state)
        saved[package] = None if backup_value is None else [str(backup_value[0]), backup_value[1]]
        if apk:
            output = adb(serial, "install", "-r", "-d", str(apk), check=False)
            print(f"install {package}: {'Success' if 'Success' in output else 'FAILED ' + output.strip()[-200:]}")
    mode = adb(serial, "shell", "appops", "get", PLUGIN, "MANAGE_EXTERNAL_STORAGE", check=False)
    saved["appops"] = "allow" if re.search(r"^MANAGE_EXTERNAL_STORAGE: allow", mode, re.M) else "default"
    saved["folders"] = sorted(existing_folders(serial))
    (state / "state.json").write_text(json.dumps(saved, ensure_ascii=False, indent=2), encoding="utf-8")
    adb(serial, "shell", "appops", "set", PLUGIN, "MANAGE_EXTERNAL_STORAGE", "allow", check=False)
    adb(serial, "shell", f"rm -rf '{REMOTE}' '{STAGING}'; mkdir -p '{REMOTE}' '{STAGING}'", check=False)
    for name, path in sources(args.ffmpeg, args.cache).items():
        push(serial, path, name)
    for key, (file_name, _) in CASES.items():
        push(serial, SAMPLES / file_name, f"sample-{key}.js")
    adb(serial, "shell", f"rm -rf '{STAGING}'", check=False)
    for package in (HOST, PLUGIN):
        version = re.search(r"versionCode=(\d+)", adb(serial, "shell", "dumpsys", "package", package, check=False))
        print(f"{package}: versionCode {version[1] if version else '-'}")
    print(f"PREPARED {serial}: samples and sources in {REMOTE}")
    return 0


def run(args: argparse.Namespace) -> int:
    serial = args.serial
    saved = json.loads((args.state / "state.json").read_text(encoding="utf-8"))
    folders_before = set(saved.get("folders", []))
    failures = 0
    results = []
    for key in [item.strip() for item in args.only.split(",") if item.strip()]:
        _, extra = CASES[key]
        out = f"{REMOTE}/result-{key}.json"
        arguments = {name: (f"{REMOTE}/{value}" if isinstance(value, str) else value) for name, value in extra.items()}
        arguments["output"] = out
        script = RUNNER % {"out": json.dumps(out), "check": "true" if key != "flac" else "false",
                           "sample": json.dumps(f"{REMOTE}/sample-{key}.js"), "arguments": json.dumps(arguments)}
        before = listing(serial)
        adb(serial, "shell", f"rm -f '{out}'", check=False)
        with tempfile.TemporaryDirectory() as temporary:
            runner = Path(temporary) / f"run-{key}.js"
            runner.write_text(script, encoding="utf-8")
            adb(serial, "push", str(runner), f"{REMOTE}/run-{key}.js")
        adb(serial, "shell", "input", "keyevent", "KEYCODE_WAKEUP", check=False)
        adb(serial, "shell", "am", "start", "-n", launcher(serial), check=False)
        time.sleep(2)
        if key in ("gif", "flac"):
            print(f"WAIT {key}: confirm the {'screen capture' if key == 'gif' else 'microphone permission (if asked)'} dialog on {serial}", flush=True)
        started = time.time()
        adb(serial, "shell", "am", "start", "-a", "android.intent.action.VIEW", "-t", "application/x-javascript",
            "-d", f"file://{REMOTE}/run-{key}.js", "-n", RUN_INTENT)
        summary = None
        while time.time() - started < args.timeout:
            raw = adb(serial, "shell", "cat", f"'{out}'", check=False)
            if raw.startswith("{"):
                summary = json.loads(raw)
                break
            time.sleep(2)
        seconds = time.time() - started
        info: dict = {}
        output = (summary or {}).get({"edit": "path", "compose": "path", "flac": "flac", "gif": "gif"}[key])
        if output:
            with tempfile.TemporaryDirectory() as temporary:
                local = Path(temporary) / Path(output).name
                adb(serial, "pull", output, str(local), check=False)
                if local.exists():
                    info = probe(args.ffmpeg, local)
                    info["sizeBytes"] = local.stat().st_size
        reason = "timed out" if summary is None else verdict(key, summary, info)
        failures += reason is not None
        values = ", ".join(f"{name} {value}" for name, value in info.items())
        print(f"{'PASS' if reason is None else 'FAIL'} {key} {seconds:.1f} s: {values}{'' if reason is None else ' | ' + reason}", flush=True)
        results.append({"case": key, "pass": reason is None, "seconds": round(seconds, 1), "summary": summary, "probe": info, "reason": reason})
        if not args.keep:
            removed = remove_new(serial, before, folders_before)
            adb(serial, "shell", f"rm -f '{out}' '{REMOTE}/run-{key}.js'", check=False)
            print(f"  removed {removed} new file(s) in the default folders", flush=True)
    if args.json:
        args.json.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"SAMPLES {len(results) - failures} / {len(results)} PASS")
    return 1 if failures else 0


def restore_all(args: argparse.Namespace) -> int:
    serial = args.serial
    saved = json.loads((args.state / "state.json").read_text(encoding="utf-8"))
    for package in (PLUGIN, HOST):
        value = saved.get(package)
        print(restore(serial, package, None if value is None else (Path(value[0]), value[1])))
    adb(serial, "shell", "appops", "set", PLUGIN, "MANAGE_EXTERNAL_STORAGE", saved.get("appops", "default"), check=False)
    adb(serial, "shell", f"rm -rf '{REMOTE}' '{STAGING}'", check=False)
    adb(serial, "shell", "content", "delete", "--uri", "content://media/external/file", "--where", f"\"_data LIKE '%{REMOTE.removeprefix('/sdcard')}%'\"", check=False)
    left = adb(serial, "shell", f"ls -d '{REMOTE}' '{STAGING}' 2>/dev/null", check=False).strip()
    print(f"RESTORED {serial}: appops {saved.get('appops', 'default')}, pushed files {'left: ' + left if left else 'removed'}")
    return 0


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--serial", required=True)
    parser.add_argument("--state", type=Path, required=True, help="folder of the APK backups and the saved state")
    parser.add_argument("--ffmpeg", default=shutil.which("ffmpeg") or DEFAULT_FFMPEG)
    parser.add_argument("--cache", type=Path, default=Path(tempfile.gettempdir()) / "slate-samples-sources")
    steps = parser.add_subparsers(dest="step", required=True)
    step = steps.add_parser("prepare")
    step.add_argument("--host-apk", type=Path)
    step.add_argument("--plugin-apk", type=Path)
    step = steps.add_parser("run")
    step.add_argument("--only", default="edit,compose,flac,gif")
    step.add_argument("--timeout", type=int, default=600, help="seconds per sample (the dialogs wait for the maintainer)")
    step.add_argument("--keep", action="store_true")
    step.add_argument("--json", type=Path)
    steps.add_parser("restore")
    args = parser.parse_args(argv)
    args.cache.mkdir(parents=True, exist_ok=True)
    if installed(args.serial, HOST) is None and args.step != "restore":
        print(f"{HOST} is not installed on {args.serial}")
    return {"prepare": prepare, "run": run, "restore": restore_all}[args.step](args)


if __name__ == "__main__":
    raise SystemExit(main())
